// Manifest records the planted differences exactly as they must be reported.
type Manifest struct {
	Seed        int64           `json:"seed"`
	Rows        int             `json:"rows"`
	Tables      []TableManifest `json:"tables"`
	GeneratedAt string          `json:"generated_at"`
}

// TableManifest is the planted difference set of one table.
type TableManifest struct {
	Name    string    `json:"name"`
	Rows    int       `json:"rows"`
	Planted []Planted `json:"planted"`
}

// Planted is one expected difference.
type Planted struct {
	PK     string `json:"pk"`
	Kind   string `json:"kind"` // missing | extra | modified
	Column string `json:"column,omitempty"`
	Old    string `json:"old,omitempty"`
	New    string `json:"new,omitempty"`
}

func SeedAll(dir string, n int, seed int64, manifestPath string) error {
	ctx := context.Background()
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	srcPath := filepath.Join(dir, "src.db")
	tgtPath := filepath.Join(dir, "tgt.db")
	for _, p := range []string{srcPath, tgtPath} {
		for _, suffix := range []string{"", "-wal", "-shm"} {
			os.Remove(p + suffix)
		}
	}
	src, err := source.Open(ctx, source.Config{Driver: model.DriverSQLite, DSN: srcPath})
	if err != nil {
		return err
	}
	defer src.Close()
	tgt, err := source.Open(ctx, source.Config{Driver: model.DriverSQLite, DSN: tgtPath})
	if err != nil {
		return err
	}
	defer tgt.Close()

	man := Manifest{Seed: seed, Rows: n, GeneratedAt: time.Now().UTC().Format(time.RFC3339)}
	for _, def := range tableDefs(n) {
		log.Printf("seeding %s: %d rows", def.name, n)
		if err := loadTable(ctx, src, def, def.srcCreate, def.srcRow, n); err != nil {
			return fmt.Errorf("%s source: %w", def.name, err)
		}
		if err := loadTable(ctx, tgt, def, def.tgtCreate, def.tgtRow, n); err != nil {
			return fmt.Errorf("%s target: %w", def.name, err)
		}
		rnd := rand.New(rand.NewSource(seed + int64(len(def.name))))
		planted, err := def.plant(ctx, tgt, rnd, n)
		if err != nil {
			return fmt.Errorf("%s plant: %w", def.name, err)
		}
		man.Tables = append(man.Tables, TableManifest{Name: def.name, Rows: n, Planted: planted})
		log.Printf("  planted %d differences", len(planted))
	}
	if err := writeManifestFile(manifestPath, man); err != nil {
		return err
	}
	log.Printf("manifest written to %s", manifestPath)
	cfg := fmt.Sprintf(demoConfigTpl, srcPath, tgtPath)
	if err := os.WriteFile(filepath.Join(dir, "config.yaml"), []byte(cfg), 0o644); err != nil {
		return err
	}
	log.Printf("config written to %s", filepath.Join(dir, "config.yaml"))
	return nil
}

func writeManifestFile(path string, man Manifest) error {
	b, err := json.MarshalIndent(man, "", "  ")
	if err != nil {
		return err
	}
	return os.WriteFile(path, b, 0o644)
}

func loadTable(ctx context.Context, db *source.Database, def tableDef, create string, rowFn func(int) []any, n int) error {
	if _, err := db.DB.ExecContext(ctx, create); err != nil {
		return err
	}
	tx, err := db.DB.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	cols := len(rowFn(0))
	ph := make([]string, cols)
	for i := range ph {
		ph[i] = "?"
	}
	stmt, err := tx.PrepareContext(ctx, "INSERT INTO "+def.name+" VALUES ("+strings.Join(ph, ",")+")")
	if err != nil {
		tx.Rollback()
		return err
	}
	for i := 0; i < n; i++ {
		if _, err := stmt.ExecContext(ctx, rowFn(i)...); err != nil {
			stmt.Close()
			tx.Rollback()
			return fmt.Errorf("row %d: %w", i, err)
		}
	}
	stmt.Close()
	return tx.Commit()
}

